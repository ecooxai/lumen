#!/usr/bin/env python3
"""Generate src/css/props_generated.inc: CSS properties Chrome supports, whether they inherit and their
initial computed values, from the Chrome WPT baseline's passing subtest names
("Property X has initial value Y", "Property X inherits", "Property X does not inherit", "Property X value ...").
Usage: tools/gen_css_props.py /path/to/chrome-base.json"""
import json, re, sys
base = json.load(open(sys.argv[1]))
props = {}
for u, c in base.items():
    if not u.startswith('/css/') or not c.get('st'): continue
    for n, v in c['st'].items():
        if v != 'PASS': continue
        m = re.match(r"Property ([a-z-]+) (has initial value (.*)|inherits|does not inherit|value )", n)
        if not m or m.group(1).startswith('--'): continue
        p = props.setdefault(m.group(1), {'inh': None, 'init': None})
        if m.group(3) is not None: p['init'] = m.group(3)
        elif m.group(2) == 'inherits': p['inh'] = True
        elif m.group(2) == 'does not inherit': p['inh'] = False
src = open('src/css/style.c').read()
body = src[src.index('char *css_get_computed_value('):]; body = body[:body.index('\n}\n')]
native = set(re.findall(r'strcmp\(prop, "([a-z-]+)"\)', body))
props.setdefault('accent-color', {'inh': True, 'init': None})['inh'] = True
# Explicit native logical property group; its serializer uses shared slots and
# cannot be inferred from direct strcmp branches in the public getter wrapper.
for axis in ('width', 'height', 'inline-size', 'block-size', 'size'):
    name = 'contain-intrinsic-' + axis
    props[name] = {'inh': False, 'init': 'none'}
    native.add(name)
for name, initial in [('column-width', 'auto'), ('column-count', 'auto'), ('columns', 'auto')]:
    props[name] = {'inh': False, 'init': initial}
    native.add(name)
for k, p in props.items():   # colour initials that are the test's currentcolor
    if k != 'color' and p['init'] and p['init'].startswith('rgb(') : p['init'] = 'currentcolor'
esc = lambda s: s.replace('\\', '\\\\').replace('"', '\\"')
out = ['/* generated by tools/gen_css_props.py: { name, inherited, natively computed, initial computed value or NULL } */']
for k in sorted(props):
    p = props[k]
    out.append('{ "%s", %d, %d, %s },' % (k, 1 if p['inh'] else 0, k in native, '"%s"' % esc(p['init']) if p['init'] is not None else 'NULL'))
open('src/css/props_generated.inc', 'w').write('\n'.join(out) + '\n')
print(len(props), 'properties;', sum(1 for p in props.values() if p['init'] is not None), 'with initial values;', sum(1 for p in props.values() if p['inh']), 'inherited')
