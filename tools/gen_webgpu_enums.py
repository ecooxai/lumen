#!/usr/bin/env python3
"""Writes src/js/webgpu_enums.inc: the WebGPU IDL enum strings wgpu-native's webgpu.h knows, keyed the way
webgpu.cc looks them up (lower case without '-' or '_'), so 'rgba8unorm-srgb' finds WGPUTextureFormat_RGBA8UnormSrgb."""
import re
import sys

ENUMS = ['TextureFormat', 'VertexFormat', 'FeatureName', 'BufferBindingType', 'TextureSampleType', 'StorageTextureAccess',
         'SamplerBindingType', 'QueryType', 'PrimitiveTopology', 'IndexFormat', 'FrontFace', 'CullMode', 'CompareFunction',
         'StencilOperation', 'BlendOperation', 'BlendFactor', 'AddressMode', 'FilterMode', 'MipmapFilterMode', 'TextureDimension',
         'TextureViewDimension', 'TextureAspect', 'LoadOp', 'StoreOp', 'VertexStepMode', 'ErrorFilter', 'PowerPreference']
SKIP = {'Undefined', 'BindingNotUsed', 'Force32'}


def main(header, out):
    text = open(header).read()
    lines = ['/* generated by tools/gen_webgpu_enums.py from wgpu-native webgpu.h; do not edit */']
    for e in ENUMS:
        for name in re.findall(r'\bWGPU%s_(\w+) = 0x' % e, text):
            if name in SKIP:
                continue
            key = name.replace('_', '').lower()
            lines.append('{ "%s", "%s", (int)WGPU%s_%s },' % (e, key, e, name))
    open(out, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
